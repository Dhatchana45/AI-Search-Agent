import os
from typing import Any

from dotenv import load_dotenv
from tavily import TavilyClient

load_dotenv()

TAVILY_API_KEY = os.getenv("TAVILY_API_KEY")


def _fail(query, message):
    return {
        "query": query,
        "provider": "tavily",
        "results": [],
        "count": 0,
        "success": False,
        "error": message,
    }


def search_web(
    query: str,
    max_results: int = 5,
    search_depth: str = "basic"
) -> dict[str, Any]:
    """Search the web using Tavily."""

    if not query or not query.strip():
        return _fail(query, "Search query cannot be empty.")

    if not TAVILY_API_KEY:
        return _fail(query, "TAVILY_API_KEY is missing from .env.")

    if search_depth not in {"basic", "advanced"}:
        search_depth = "basic"

    try:
        client = TavilyClient(api_key=TAVILY_API_KEY)

        response = client.search(
            query=query.strip(),
            search_depth=search_depth,
            max_results=max(1, min(max_results, 20)),
            include_answer=True,
        )

        results = []
        for item in response.get("results", []):
            results.append({
                "title": item.get("title", ""),
                "url": item.get("url", ""),
                "content": item.get("content", ""),
                "score": item.get("score", 0),
                "published_date": item.get("published_date"),
                "provider": "tavily",
            })

        return {
            "query": query,
            "provider": "tavily",
            "answer": response.get("answer", ""),
            "results": results,
            "count": len(results),
            "success": True,
            "error": None,
        }

    except Exception as exc:
        return _fail(query, f"Web search failed: {exc}")


def process_web_searches(
    searches: list[dict[str, Any]],
    max_results_per_query: int = 5,
    errors: list[str] | None = None,
) -> list[dict[str, Any]]:
    """
    Process Tavily queries generated by query_search.py.

    `errors` (optional) receives failure messages so the UI can show them.
    """

    all_results = []
    seen_urls = set()

    for search in searches:
        provider = str(search.get("provider", "")).lower()
        if provider not in {"tavily", "web", "web_search"}:
            continue

        search_query = search.get("search_query", "")
        if not search_query:
            continue

        response = search_web(query=search_query, max_results=max_results_per_query)

        if not response["success"]:
            message = f"Web search failed for '{search_query}': {response['error']}"
            print(message)
            if errors is not None:
                errors.append(message)
            continue

        for result in response["results"]:
            url = result.get("url", "")
            if url and url in seen_urls:
                continue
            if url:
                seen_urls.add(url)

            result["query"] = search_query
            # Keep the category the search was made for (used as a fallback
            # label when the page content gives no clearer hint).
            result["category"] = search.get("category", "General Web")
            all_results.append(result)

    return all_results