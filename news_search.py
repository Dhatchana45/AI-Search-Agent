import os
import requests
from dotenv import load_dotenv
from typing import Any

load_dotenv()

GNEWS_API_URL = "https://gnews.io/api/v4/search"
GNEWS_API_KEY = os.getenv("GNEWS_API_KEY")


def _fail(query, provider, message):
    return {
        "query": query,
        "provider": provider,
        "articles": [],
        "count": 0,
        "success": False,
        "error": message,
    }


def search_news(
    query: str,
    max_results: int = 10,
    language: str = "en"
) -> dict[str, Any]:
    """Search for news articles using the GNews API."""

    if not query or not query.strip():
        return _fail(query, "gnews", "Search query cannot be empty.")

    if not GNEWS_API_KEY:
        return _fail(query, "gnews", "GNEWS_API_KEY is missing from the .env file.")

    params = {
        "q": query.strip(),
        "lang": language,
        # FIX: was max(10, ...), which forced at least 10 results and made
        # the max_results argument useless for smaller values.
        "max": max(1, min(max_results, 100)),
        "sortby": "publishedAt",
        "apikey": GNEWS_API_KEY,
    }

    try:
        response = requests.get(GNEWS_API_URL, params=params, timeout=20)
        response.raise_for_status()
        data = response.json()

        articles = []
        for item in data.get("articles", []):
            source = item.get("source") or {}
            articles.append({
                "title": item.get("title", ""),
                "description": item.get("description", ""),
                "content": item.get("content", ""),
                "url": item.get("url", ""),
                "image": item.get("image", ""),
                "published_at": item.get("publishedAt", ""),
                "source": source.get("name", ""),
                "query": query,
                "provider": "gnews",
            })

        return {
            "query": query,
            "provider": "gnews",
            "articles": articles,
            "count": len(articles),
            "success": True,
            "error": None,
        }

    except requests.exceptions.HTTPError as exc:
        status_code = exc.response.status_code if exc.response is not None else None
        return _fail(query, "gnews", f"GNews HTTP error ({status_code}): {exc}")

    except requests.exceptions.RequestException as exc:
        return _fail(query, "gnews", f"News request failed: {exc}")

    except ValueError as exc:
        return _fail(query, "gnews", f"Invalid JSON response: {exc}")


def process_news_searches(
    searches: list[dict[str, Any]],
    max_results_per_query: int = 10,
    errors: list[str] | None = None,
) -> list[dict[str, Any]]:
    """
    Process news queries generated by query_search.py.
    Only searches marked with the GNews provider are processed.

    `errors` (optional) receives failure messages so the UI can show them
    instead of only printing to the console.
    """

    all_articles = []
    seen_urls = set()

    for search in searches:
        if str(search.get("provider", "")).lower() != "gnews":
            continue

        search_query = search.get("search_query", "")
        result = search_news(query=search_query, max_results=max_results_per_query)

        if not result["success"]:
            message = f"News search failed for '{search_query}': {result['error']}"
            print(message)
            if errors is not None:
                errors.append(message)
            continue

        for article in result["articles"]:
            url = article.get("url", "")
            if url and url in seen_urls:
                continue
            if url:
                seen_urls.add(url)
            article["category"] = search.get("category", "News")
            all_articles.append(article)

    return all_articles